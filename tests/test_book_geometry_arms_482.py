def _day(overrides: dict, filler=None, d=FILL_DAY):
    """A FULL regular session of 1-minute bars (09:30-15:59) on `d`: a quiet 10.3 band in the first
    hour, 10.4 until 10:45, then a 11.2 plateau, with `overrides` {(h, m): (o, h, l, c)} laid on top.
    `filler` replaces the post-10:30 band entirely."""
    out = []
    t = datetime(d.year, d.month, d.day, 9, 30, tzinfo=_ET)
    while t.time() < time(16, 0):
        key = (t.hour, t.minute)
        if key in overrides:
            o, h, l, c = overrides[key]
        elif t.time() < time(10, 30):
            o, h, l, c = (10.3, 10.35, 10.25, 10.3)
        elif filler is not None:
            o, h, l, c = filler
        elif t.time() <= time(10, 45):
            o, h, l, c = (10.4, 10.45, 10.35, 10.4)
        else:
            o, h, l, c = (11.2, 11.3, 11.1, 11.2)
        out.append({"m": t, "o": o, "h": h, "l": l, "c": c})
        t += timedelta(minutes=1)
    return out


