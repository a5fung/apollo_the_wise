def _wire_book(monkeypatch, *, trade=None, minutes=None, sessions=None, pre=None, day0_high=None, **kw):
    trade = trade if trade is not None else base._trade_row()
    sessions = sessions if sessions is not None else SESS
    daily = (pre if pre is not None else base._pre_rows()) + [{"trade_date": s, "open_price": b["o"], "high_price": b["h"],
                                 "low_price": b["l"], "close": b["c"]} for s, b in sessions]
    if day0_high is not None:     # the fill day's own stored daily bar (the day-0 gap rule reads only its high)
        fd = trade["filled_at"].astimezone(_ET).date()
        daily.append({"trade_date": fd, "open_price": 10.0, "high_price": day0_high, "low_price": 9.5, "close": 10.0})
    wired = base._wire(monkeypatch, trade=trade, daily=daily, minutes=(minutes if minutes is not None else STD), **kw)
    audits = wired[2]

    async def audit(event_type, summary, detail=""):
        audits.append((event_type, summary))

    async def get_pool():
        return await db.get_pool()

    monkeypatch.setattr(bga, "log_audit_event", audit)
    monkeypatch.setattr(bga, "get_pool", get_pool)
    return wired


