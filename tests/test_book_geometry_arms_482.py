def test_capped_dollars_size_off_the_trigger_and_score_off_the_fill():
    """Review F5. frac = min(mult x (fill-stop)/(trigger-stop), 20% x (fill-stop)/(trigger x risk_pct))."""
    after = date(2026, 10, 14)                  # 2% era
    # filled AT the trigger, a 10% stop: budget term 1.0, cap term 0.2 x 1/(10 x 0.02) = 1.0 -> 1.0, not binding
    c = bga.capped_dollar_scoring(10.0, 9.0, 10.0, "Bull", 0.5, after)
    assert c["sizing_risk_pct"] == 0.02 and c["sizing_regime_mult"] == 1.0
    assert c["risk_frac_capped"] == pytest.approx(1.0) and c["cap_binding"] is False
    assert c["realized_r_capped"] == pytest.approx(0.5)
    # a 5% stop at 2%: the cap term 0.5 < 1.0 binds -> half the risk is placed
    c = bga.capped_dollar_scoring(10.0, 9.5, 10.0, "Bull", 2.0, after)
    assert c["risk_frac_capped"] == pytest.approx(0.5) and c["cap_binding"] is True
    assert c["realized_r_capped"] == pytest.approx(1.0)
    # the same stop on a 1%-era fill: the cap term doubles to 1.0 -> it no longer binds
    c = bga.capped_dollar_scoring(10.0, 9.5, 10.0, "Bull", 2.0, date(2026, 9, 1))
    assert c["sizing_risk_pct"] == 0.01 and c["risk_frac_capped"] == pytest.approx(1.0)
    # PENG's geometry: sized for $7.00/share at the $69.20 trigger, carried $10.01 from the $72.21 fill ->
    # 1.43 full R placed by the budget (the cap term 0.2 x 10.01/(69.2 x 0.02) = 1.446 does not bind)
    c = bga.capped_dollar_scoring(72.21, 62.20, 69.20, "Bull", 1.0, date(2026, 10, 7))
    assert c["risk_frac_capped"] == pytest.approx(10.01 / 7.00) and c["cap_binding"] is False
    assert c["realized_r_capped"] == pytest.approx(10.01 / 7.00)
    # regime multiplier; an unrecognised label floors at 0.25
    assert bga.capped_dollar_scoring(10.0, 9.0, 10.0, "Choppy", 1.0, after)["risk_frac_capped"] == pytest.approx(0.75)
    assert bga.capped_dollar_scoring(10.0, 9.0, 10.0, "???", 1.0, after)["sizing_regime_mult"] == 0.25
    # no settled R -> the sizing columns still land, the dollar-R does not; no stop / no trigger -> all NULL
    c = bga.capped_dollar_scoring(10.0, 9.5, 10.0, "Bull", None, after)
    assert c["risk_frac_capped"] == pytest.approx(0.5) and c["realized_r_capped"] is None
    for bad in ((10.0, None, 10.0), (10.0, 10.0, 10.0), (10.0, 9.0, None), (10.0, 9.0, 9.0)):
        assert all(v is None for v in bga.capped_dollar_scoring(*bad, "Bull", 1.0, after).values()), bad


