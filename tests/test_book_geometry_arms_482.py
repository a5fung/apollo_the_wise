@pytest.mark.asyncio
async def test_the_job_runs_the_book_arms_after_the_original_each_in_its_own_guard(monkeypatch):
    """The 18:04 job: the original recorder first, then the book arms; a failure in EITHER is paged under its
    own name and never stops the other; each gets its own failure-rate check on `arms_considered`."""
    from agents.market_intelligence import health_checks
    from agents.market_intelligence import scheduler as sched
    calls, pages, rates = [], [], []

    def counters(**over):
        c = {"population": 1, "arms_considered": 2, "written": 2, "pending": 0, "errors": 0, "settled": 2,
             "abstained": 0, "unscoreable": 0, "horizon": 0, "fills_considered": 1}
        c.update(over)
        return c

    async def rate(job, out, attempted_key):
        rates.append((job, attempted_key))
        return False

    async def page(job, err):
        pages.append(job)

    monkeypatch.setattr(health_checks, "check_recorder_failure_rate", rate)
    monkeypatch.setattr(sched, "notify_job_failure", page)

    def runner(name, fail=False, extra=None):
        async def run(*a, **k):
            calls.append(name)
            if fail:
                raise RuntimeError(f"{name} down")
            return counters(**(extra or {}))
        return run

    book_extra = dict(fill_facts=1, pending_open_walk=0, pending_data_gap=0, no_entry=0)
    for orig_fail, book_fail in ((False, False), (True, False), (False, True)):
        calls.clear(), pages.clear(), rates.clear()
        monkeypatch.setattr(lfc, "run_live_fill_counterfactuals", runner("original", orig_fail))
        monkeypatch.setattr(bga, "run_book_geometry_arms", runner("book", book_fail, book_extra))
        await sched._live_fill_counterfactuals_job()
        assert calls == ["original", "book"], (orig_fail, book_fail)
        assert pages == ([("live_fill_counterfactuals")] if orig_fail else []) + (["book_geometry_arms"] if book_fail else [])
        assert rates == ([] if orig_fail else [("live_fill_counterfactuals", "arms_considered")]) + \
            ([] if book_fail else [("book_geometry_arms", "arms_considered")])


