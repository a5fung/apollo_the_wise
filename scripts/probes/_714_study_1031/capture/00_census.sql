\echo '=== CENSUS_SCORED_BY_DATE'
-- deduped scored rows per scan date; float era is read from this
WITH raw AS (
  SELECT * FROM mi_ep_scan_log WHERE scan_date >= DATE '2026-04-13' AND ep_score IS NOT NULL),
scored AS (
  SELECT DISTINCT ON (ticker, scan_date) *
  FROM raw
  ORDER BY ticker, scan_date,
           (filter_reason IS NULL AND score_tier IS NOT NULL) DESC, ep_score DESC NULLS LAST, scan_time_et DESC NULLS LAST)
SELECT scan_date,
  count(*) AS n_scored,
  count(float_shares) AS n_float_nonnull,
  count(*) FILTER (WHERE float_shares > 0 AND float_shares < 50000000) AS n_float_lt_50m,
  count(score_breakdown) AS n_breakdown,
  count(*) FILTER (WHERE (score_breakdown->>'float')::numeric > 0) AS n_float_points,
  count(market_cap) AS n_mcap_nonnull,
  count(*) FILTER (WHERE filter_reason IS NULL AND score_tier IS NOT NULL) AS n_alerted,
  count(ep_bar) AS n_bar
FROM scored GROUP BY scan_date ORDER BY scan_date;
