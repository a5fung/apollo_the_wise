-- the 8 labelled EPs: what each source holds
WITH lab(ticker, scan_date) AS (VALUES
  ('BFLY', DATE '2026-06-18'),
  ('PLTR', DATE '2026-08-04'),
  ('ABNB', DATE '2026-08-07'),
  ('TEAM', DATE '2026-08-07'),
  ('HTFL', DATE '2026-08-14'),
  ('MRNA', DATE '2026-08-19'),
  ('CHPT', DATE '2026-09-03'),
  ('PENG', DATE '2026-10-07'))
SELECT lab.ticker, lab.scan_date,
  (SELECT count(*) FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date) AS n_scan_rows,
  (SELECT count(*) FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date AND l.ep_score IS NOT NULL) AS n_scored_rows,
  (SELECT max(l.ep_score) FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date) AS best_score,
  (SELECT max(l.float_shares) FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date) AS float_any_tick,
  (SELECT count(l.score_breakdown) FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date) AS n_breakdown_ticks,
  (SELECT string_agg(DISTINCT regexp_replace(coalesce(l.filter_reason, 'NULL'), '[|\r\n]+', ' ', 'g'), ' ;; ')
     FROM mi_ep_scan_log l WHERE l.ticker = lab.ticker AND l.scan_date = lab.scan_date) AS filter_reasons,
  (SELECT count(*) FROM mi_ep_alerts a WHERE a.ticker = lab.ticker AND a.alert_date = lab.scan_date AND COALESCE(a.source, 'live') = 'live') AS n_live_alerts,
  (SELECT count(*) FROM mi_daily_closes d WHERE d.ticker = lab.ticker AND d.trade_date < lab.scan_date) AS n_hist_bars,
  (SELECT min(d.trade_date) FROM mi_daily_closes d WHERE d.ticker = lab.ticker) AS hist_start,
  (SELECT count(*) FROM mi_daily_closes d WHERE d.ticker = lab.ticker AND d.trade_date = lab.scan_date) AS bar_on_day,
  (SELECT count(*) FROM mi_daily_closes d WHERE d.ticker = lab.ticker AND d.trade_date > lab.scan_date) AS n_bars_after,
  (SELECT count(*) FROM mi_daily_closes d WHERE d.ticker = lab.ticker AND d.trade_date < lab.scan_date AND (d.high_price IS NULL OR d.low_price IS NULL)) AS n_hist_bars_missing_hl
FROM lab ORDER BY lab.scan_date, lab.ticker;
\echo '=== CENSUS_LABELLED_BOARDS'
-- board sizes on the 7 distinct labelled dates
WITH lab(ticker, scan_date) AS (VALUES
  ('BFLY', DATE '2026-06-18'),
  ('PLTR', DATE '2026-08-04'),
  ('ABNB', DATE '2026-08-07'),
  ('TEAM', DATE '2026-08-07'),
  ('HTFL', DATE '2026-08-14'),
  ('MRNA', DATE '2026-08-19'),
  ('CHPT', DATE '2026-09-03'),
  ('PENG', DATE '2026-10-07')),
rows_ AS (
  SELECT DISTINCT ON (l.ticker, l.scan_date) l.ticker, l.scan_date, l.ep_score, l.filter_reason, l.score_tier
  FROM mi_ep_scan_log l
  WHERE l.scan_date IN (SELECT DISTINCT scan_date FROM lab)
  ORDER BY l.ticker, l.scan_date, (l.ep_score IS NOT NULL) DESC,
           (l.filter_reason IS NULL AND l.score_tier IS NOT NULL) DESC, l.ep_score DESC NULLS LAST, l.scan_time_et DESC NULLS LAST)
SELECT r.scan_date,
  count(*) AS n_logged_tickers,
  count(*) FILTER (WHERE r.ep_score IS NOT NULL) AS n_scored_tickers,
  count(*) FILTER (WHERE r.ep_score IS NOT NULL AND NOT EXISTS (SELECT 1 FROM lab WHERE lab.ticker = r.ticker AND lab.scan_date = r.scan_date)) AS n_scored_rivals,
  count(*) FILTER (WHERE r.filter_reason IS NULL AND r.score_tier IS NOT NULL) AS n_alerted_tickers,
  (SELECT string_agg(lab.ticker, ',' ORDER BY lab.ticker) FROM lab WHERE lab.scan_date = r.scan_date) AS labelled_here
FROM rows_ r GROUP BY r.scan_date ORDER BY r.scan_date;
\echo '=== CENSUS_BARS_FRESHNESS'
-- daily bars: last loaded session, and SPY's last 20 sessions = the calendar
SELECT d.trade_date, count(*) AS n_rows, count(*) FILTER (WHERE d.ticker = 'SPY') AS spy_rows
FROM mi_daily_closes d
WHERE d.trade_date >= (SELECT max(trade_date) FROM mi_daily_closes) - 40
GROUP BY d.trade_date ORDER BY d.trade_date;
