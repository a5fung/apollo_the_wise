"""#146 detection page (2026-10-11) — emit the two large SELECT-only pulls from the captured candidate list.

  q2_bars.sql    OHLCV for every q1 candidate + the corpus tickers, trade_date >= 2023-12-01 (262 trading rows of
                 history before the 2025-01-02 window start, as get_recent_daily_history(…, 262, end_date=d) slices it)
  q4_scores.sql  mi_stock_scores (rs_rank, rs_1m) for the same tickers, every score_date the table has (2025-12-26 →),
                 so the RS half of get_flag_universe can be re-read for 2026 scan dates. 2025 cannot be tagged.

Run from the repo root:  python scripts/probes/_146_page/gen_pull_sql.py
Then (captured ONCE each, gzipped on the remote):
  ssh apollo@87.99.134.162 "docker exec -i apollo-postgres psql -U apollo -d apollo -A -F \\$'\\t' | gzip" \
      < scripts/probes/_146_page/q2_bars.sql > scripts/probes/_146_page/q2_bars.tsv.gz
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
# Every name the corpus cross-check reads, whether or not the pre-filter admitted it.
CORPUS = ("CDNA", "HNGE", "MRNA", "NCI", "ATAI", "OUST", "SHAZ", "REPL", "GH", "HPE")


def candidates():
    out = []
    for ln in open(os.path.join(HERE, "q1_candidates.out")):
        p = ln.rstrip("\n").split("\t")
        if len(p) < 8 or p[0] == "ticker" or p[0].startswith("("):
            continue
        out.append(p[0])
    return out


def main():
    tick = sorted(set(candidates()) | set(CORPUS))
    lit = ", ".join("'" + t.replace("'", "''") + "'" for t in tick)
    with open(os.path.join(HERE, "q2_bars.sql"), "w") as fh:
        fh.write("-- #146 detection page: raw daily bars for the replay population (q1 candidates + corpus). SELECT-only.\n")
        fh.write(f"-- {len(tick)} tickers. Generated by gen_pull_sql.py; do not hand-edit.\n")
        fh.write("SELECT ticker, trade_date, open_price, high_price, low_price, close, volume\n"
                 "FROM mi_daily_closes\n"
                 f"WHERE trade_date >= '2023-12-01' AND ticker IN ({lit})\n"
                 "ORDER BY ticker, trade_date;\n")
    with open(os.path.join(HERE, "q4_scores.sql"), "w") as fh:
        fh.write("-- #146 detection page: the RS half of get_flag_universe (rs_rank <= 200 OR rs_1m >= 80) for the replay\n")
        fh.write("-- population, every score_date the table holds (first row 2025-12-26). SELECT-only.\n")
        fh.write(f"-- {len(tick)} tickers. Generated by gen_pull_sql.py; do not hand-edit.\n")
        fh.write("SELECT ticker, score_date, rs_rank, rs_1m\n"
                 "FROM mi_stock_scores\n"
                 f"WHERE ticker IN ({lit})\n"
                 "ORDER BY ticker, score_date;\n")
    # the per-date row counts the universe's latest_complete_score_date_sql reads (a stray single-row day is skipped)
    with open(os.path.join(HERE, "q5_score_days.sql"), "w") as fh:
        fh.write("-- #146 detection page: rows per score_date, to re-derive latest_complete_score_date_sql per scan date. SELECT-only.\n")
        fh.write("SELECT score_date, COUNT(*) AS n FROM mi_stock_scores GROUP BY score_date ORDER BY score_date;\n")
    print(f"{len(tick)} tickers -> q2_bars.sql, q4_scores.sql, q5_score_days.sql")


if __name__ == "__main__":
    main()
