def keyval(r, col, sign):
    v = r[col]
    return None if v is None else sign * v


def order(rs, name):
    if name == "A":
        k = lambda r: shortlist_sort_key(r["ticker"], r["compA"], None)
    elif name == "B":
        k = lambda r: shortlist_sort_key(r["ticker"], r["compB"], r["k1_adv_dollar"])
    else:
        kind, kid = name.split(":")
        _, col, sign, _ = next(x for x in KEYS if x[0] == kid)

        def k(r, col=col, sign=sign, kind=kind):
            v = keyval(r, col, sign)
            miss = (1, 0.0) if v is None else (0, -v)
            return ((-r["compB"],) if kind == "T" else ()) + miss + (r["ticker"],)
    return sorted(rs, key=k)


