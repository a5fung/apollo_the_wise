def auc_key(group: set[str], col: str, sign: int, present_only: bool, lower_is_better=False):
    """share of (labelled, unlabelled same-day pool-mate) pairs where the labelled name's key is
    better; ties 0.5; missing = worst. Returns (auc, n_labelled, n_pairs, n_label_missing)."""
    num = n = 0.0
    used = set()
    miss = 0
    for d, rs in days.items():
        if col == "k5_zones" and d not in zones_days:
            continue
        labs = [r for r in rs if r["label"] in group]
        mates = [r for r in rs if not r["label"]]
        for L in labs:
            lv = keyval(L, col, sign)
            if lv is None:
                miss += 1
            for m in mates:
                mv = keyval(m, col, sign)
                if present_only and (lv is None or mv is None):
                    continue
                used.add((d, L["ticker"]))
                n += 1
                if lv is None and mv is None:
                    num += 0.5
                elif mv is None:
                    num += 1
                elif lv is None:
                    pass
                elif lv > mv:
                    num += 1
                elif lv == mv:
                    num += 0.5
    return (num / n if n else None), len(used), int(n), miss


def auc_order(group: set[str], o: str):
    num = n = 0
    used = set()
    for d, rs in days.items():
        labs = [r for r in rs if r["label"] in group]
        mates = [r for r in rs if not r["label"]]
        for L in labs:
            for m in mates:
                used.add((d, L["ticker"]))
                n += 1
                num += int(rank[o][(d, L["ticker"])] < rank[o][(d, m["ticker"])])
    return (num / n if n else None), len(used), n


